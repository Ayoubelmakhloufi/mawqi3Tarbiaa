<h2>6. مراحل المباراة</h2>
<p>ولوج السنة الأولى يتم بعد النجاح في <b>امتحان الباكالوريا</b> ثم في مباراة من مرحلتين:</p>

<h3>المرحلة 1 — الانتقاء التمهيدي (75%)</h3>
<p>
  يمثل <b>75% من المعدل العام للقبول</b>، ويُحتسب بناءً على معدل الامتحان الوطني ومعدل الامتحان الجهوي
  للباكالوريا، مضروبين في <b>معامل الترجيح</b> حسب الشعبة المحصّل عليها.
</p>
<div class="note-ok">
  <b>احسب معدلك الآن</b> عبر <a href="/حساب_معدل_الانتقاء">حاسبة معدل الانتقاء</a> —
  معاملاتها مطابقة حرفيًا للملحق الرسمي رقم 2 لهذه السنة.
  والشرح المفصّل في <a href="/maqalat/charh-hisab-mouaddal-intiqa">كيف يُحسب معدل الانتقاء</a>.
</div>
<p>
  المنتقَون يحمّلون <b>بطاقة الاستدعاء</b> من البوابة ويطبعونها، وتتضمن تاريخ ومكان الاختبار الشفوي.
</p>

<h3>المرحلة 2 — الاختبار الشفوي (25%)</h3>
<p>
  يمثل <b>25% من المعدل العام للقبول</b>. يحضره المترشح مصحوبًا بـ<b>البطاقة الوطنية للتعريف الإلكترونية
  وبطاقة الاستدعاء</b> — وهما وثيقتان إجباريتان لاجتياز الاختبار.
</p>
<div class="note">
  <b>⚠️ النقطة الإقصائية:</b> أي درجة <b>أقل من 5 من 20</b> في الاختبار الشفوي
  <b>موجبة للإقصاء من المباراة</b> — مهما كان معدل انتقائك التمهيدي مرتفعًا.
  <br><br>
  للتحضير الجاد، اطّلع على قسم الاستعداد للشفوي في
  <a href="/maqalat/masar-ijaza-tarbiya">مسار الإجازة في التربية</a>.
</div>

<h2>7. كيف يتم تعيين المقبولين؟</h2>
<p>يعتمد التعيين على ثلاثة معايير مجتمعة:</p>
<ol>
  <li><b>درجة الاستحقاق</b> بناءً على المعدل العام (75% انتقاء + 25% شفوي).</li>
  <li><b>ترتيب اختياراتك</b> كما عبّرت عنه أثناء التسجيل.</li>
  <li><b>عدد المقاعد المتوفرة</b> في كل مسلك ومؤسسة.</li>
</ol>

<h3>قواعد حاسمة يجهلها كثيرون</h3>
<ul>
  <li>
    <b>التعيين في اختيار متقدّم يُلغي ما بعده:</b> إذا عُيّنت في أفضل تكوين ضمن ترتيبك،
    تُلغى تلقائيًا ونهائيًا كل التكوينات التي تليه. <b>رتّب اختياراتك بعناية شديدة.</b>
  </li>
  <li>
    <b>من لم يؤكد تسجيله النهائي يُعوَّض</b> بمترشح من لائحة الانتظار حسب الاستحقاق.
  </li>
  <li>
    <b>التسجيل النهائي</b> يتم بإيداع <b>النسخة الأصلية لشهادة الباكالوريا</b> في المؤسسة المقبول فيها.
  </li>
  <li>
    <b>تحسين الاختيار:</b> من يرغب فيه يضغط زر «تحسين الاختيار» على المنصة،
