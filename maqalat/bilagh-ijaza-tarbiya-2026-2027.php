  </li>
</ul>

<h2>8. نصائح عملية قبل أن تسجّل</h2>
<ol>
  <li><b>تحقق من أهليتك أولًا:</b> السن + الشعبة + سنة الباكالوريا. لا معنى للتخطيط قبل ذلك.</li>
  <li><b>احسب معدلك في كل مسلك تفكر فيه</b> — المعامل يختلف والفارق قد يقلب نتيجتك.</li>
