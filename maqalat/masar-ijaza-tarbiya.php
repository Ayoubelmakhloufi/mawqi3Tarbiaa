<p>
  الإجازة في التربية مسار مختلف عن الإجازات الجامعية المعتادة: يُنتقى إليه الطالب مباشرة بعد الباكالوريا،
  ويُبنى تكوينه منذ السنة الأولى على فكرة أن يصبح <b>أستاذًا</b>، لا أن يتخصص أولًا ثم يتعلم التدريس لاحقًا.
</p>

<h2>أين تُدرَّس؟</h2>
<ul>
  <li><b>ENS</b> — المدارس العليا للأساتذة.</li>
  <li><b>ESEF</b> — المدارس العليا للتربية والتكوين.</li>
  <li><b>FSE</b> — كليات علوم التربية.</li>
</ul>
<p>
  تختلف هذه المؤسسات في تبعيتها الجامعية وفي عرض التخصصات المتاح بكل واحدة،
  لكن منطق الانتقاء وبنية التكوين متقاربان بينها.
</p>

<h2>المرحلة 1: الانتقاء</h2>
<h3>أ. الانتقاء الأولي</h3>
<p>يتم آليًا انطلاقًا من نقط الباكالوريا وفق الصيغة:</p>
<div class="note-ok">
  <b>معدل الانتقاء = (الوطني × 0.75 + الجهوي × 0.25) × معامل الترجيح</b>
</div>
<p>
  و<b>معامل الترجيح</b> يُحدَّد حسب التقاطع بين التخصص المرغوب وشعبة الباكالوريا.
  الشرح المفصّل في مقال <a href="/maqalat/charh-hisab-mouaddal-intiqa">كيف يُحسب معدل الانتقاء</a>،
  ويمكنك حساب معدلك مباشرة عبر <a href="/حساب_معدل_الانتقاء">الحاسبة</a>.
</p>

<h3>ب. المباراة الشفوية</h3>
<p>
  يُستدعى إليها المترشحون الناجحون في الانتقاء الأولي. تقيّم الملاءمة للمهنة والقدرة على التواصل
  والدافعية والتصوّر المهني. وتُحتسب عادةً بنسبة <b>25%</b> مقابل <b>75%</b> لنقطة الانتقاء
  في تحديد الترتيب النهائي.
</p>

<h2>المرحلة 2: التكوين (ثلاث سنوات)</h2>
<p>يقوم التكوين على ثلاثة أعمدة متوازية منذ البداية:</p>
<ol>
  <li>
    <b>التكوين التخصصي:</b> تعميق المادة التي ستدرّسها — رياضيات، لغة، علوم، اقتصاد…
    بمستوى جامعي يفوق ما ستدرّسه، لأن الأستاذ يحتاج هامشًا معرفيًا واسعًا.
  </li>
  <li>
    <b>التكوين التربوي:</b> علوم التربية، <a href="/maqalat/nadariyat-attaallom">نظريات التعلم</a>،
    <a href="/maqalat/didaktik-3ama-wa-khassa">الديداكتيك</a>، التقويم، علم النفس التربوي،
    سوسيولوجيا التربية، وتكنولوجيا التعليم.
  </li>
  <li>
    <b>التداريب الميدانية:</b> فترات بمؤسسات التعليم تتدرج من الملاحظة إلى الممارسة المؤطَّرة.
    هذا العمود هو ما يميّز المسلك فعليًا — فالطالب يواجه القسم الحقيقي مبكرًا.
  </li>
</ol>
<p>
  ويُتوَّج المسار عادةً بـ<b>مشروع نهاية الدراسة</b> يعالج إشكالًا تربويًا أو ديداكتيكيًا.
</p>

<h2>المرحلة 3: ماذا بعد التخرج؟</h2>
<div class="note">
  <b>نقطة أساسية:</b> الإجازة في التربية <b>لا تعني التوظيف المباشر</b>.
  هي شهادة جامعية، والتوظيف يمرّ عبر
  <a href="/mobarat-attaalim/">مباراة الولوج إلى المراكز الجهوية لمهن التربية والتكوين</a> كما لباقي المترشحين.
</div>
<p>الميزة الحقيقية للخريج أنه يدخل المباراة بـ:</p>
<ul>
  <li>تكوين بيداغوجي وديداكتيكي مسبق يغطي جوهر الاختبار الكتابي.</li>
  <li>تجربة ميدانية حقيقية داخل الأقسام تخدمه في الاختبار الشفوي.</li>
  <li>معرفة مباشرة بواقع المهنة تجعل تصوّره المهني ناضجًا لا نظريًا.</li>
</ul>
<p>وتبقى أمامه آفاق أخرى: متابعة الماستر والدكتوراه في علوم التربية، أو العمل في مجالات التكوين والمواكبة التربوية.</p>

<h2>أسئلة يطرحها المترشحون كثيرًا</h2>
<p>
