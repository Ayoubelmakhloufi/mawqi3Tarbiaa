<h2>مراحل المشروع</h2>

<h3>1. الانطلاق وإثارة الحاجة</h3>
<p>
  ينطلق المشروع من <b>سؤال أو حاجة حقيقية</b>: «كيف نعرّف زوار المؤسسة بحيّنا؟»،
  «كيف نقلّص نفايات القسم؟». تجنّب البدء بـ«سننجز مشروعًا عن…» — فالمشروع المفروض
  يفقد أهم ما فيه.
</p>

<h3>2. التخطيط التشاركي</h3>
<p>هنا يُبنى <b>عقد المشروع</b> مع المتعلمين، ويجب أن يكون مكتوبًا ومعلنًا:</p>
<ul>
  <li>ما <b>المنتوج</b> المستهدف بالضبط؟ ومن سيتلقاه؟</li>
  <li>ما <b>المهام</b> اللازمة؟ ومن يتكفل بكل مهمة؟</li>
  <li>ما <b>الآجال</b> ومحطات التتبع؟</li>
  <li>ما <b>معايير التقويم</b>؟ (تُعلَن قبل البدء لا بعده)</li>
</ul>

<h3>3. الإنجاز</h3>
<p>
