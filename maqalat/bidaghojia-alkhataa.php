  <li><b>صنّف</b> حسب المصدر لا حسب الحدّة.</li>
  <li><b>جمّع</b> المتعلمين حسب <b>نوع التعثر</b> لا حسب المستوى العام.</li>
  <li><b>تدخّل</b> بما يناسب كل مجموعة — <a href="/maqalat/bidaghojia-alfariqiya">البيداغوجيا الفارقية</a>.</li>
