<h2>على ماذا نفرّق؟ ثلاثة مداخل</h2>

<h3>1. التفريق بالمضامين</h3>
<p>
  تعديل <b>ما</b> يشتغل عليه المتعلم مع بقاء الهدف واحدًا: نصوص بمستويات لغوية متفاوتة حول
  الموضوع نفسه، عدد مختلف من التمارين، معطيات مبسّطة أو مركّبة حسب المجموعة، أو تمرين متدرج
  الصعوبة على الورقة نفسها.
</p>

<h3>2. التفريق بالمسارات (السيرورات)</h3>
<p>
  تعديل <b>كيف</b> يشتغل: مجموعة تشتغل باستنباط من أمثلة، وأخرى بقاعدة معطاة تُطبَّق،
  وثالثة عبر دعامة بصرية أو محسوسة. أو تنويع شكل العمل: فردي، ثنائي، مجموعات، تعلم بالأقران.
</p>

<h3>3. التفريق بالمنتوج</h3>
<p>
  تعديل <b>كيف يُبرهن</b> المتعلم على التعلم: نص مكتوب، عرض شفوي، خطاطة، جدول، ملصق، تسجيل صوتي،
  عرض رقمي. الكفاية واحدة والدليل عليها متعدد — وهذا يفتح الباب لمتعلمين يعرفون لكنهم يعجزون
  عن التعبير بالشكل الوحيد المعتاد.
</p>

