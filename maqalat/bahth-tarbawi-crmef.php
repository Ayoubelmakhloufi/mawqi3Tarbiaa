<h2>أخطاء تُضعف البحث</h2>

<ul>
  <li><b>البدء متأخرًا.</b> البحث الذي يبدأ في الأسابيع الأخيرة لا يملك حالة أولية ولا مدة تتبع.</li>
  <li><b>تغيير عدة أشياء دفعة واحدة</b>، فلا تعرف أيّها أحدث الأثر.</li>
  <li><b>الإطار النظري المنفصل.</b> عشرون صفحة عن النظريات لا يعود إليها التحليل حشو. اقرأ ما تحتاجه لتدخّلك فقط.</li>
  <li><b>ادّعاء نتائج قاطعة.</b> قسم واحد وبضعة أسابيع لا يسمحان بتعميم. قل «لوحظ في هذا القسم» لا «ثبت أن».</li>
  <li><b>إخفاء ما لم ينجح.</b> ذكر الحدود يرفع مصداقيتك ولا يخفضها.</li>
</ul>

