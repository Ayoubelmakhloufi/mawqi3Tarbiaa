<h2>3. الخلط بين الشدة والضبط</h2>

<p>
  يظن كثير من المبتدئين أن الضبط يُبنى بالصرامة في الأسابيع الأولى. والواقع أن ما يبنيه
  هو <b>الثبات</b>: قواعد قليلة، واضحة، صيغت مع المتعلمين، وتُطبَّق في كل مرة بالطريقة نفسها.
</p>

<div class="note">
  قاعدة تُطبَّق مرة وتُهمل مرتين تعلّم القسم أن الأمر <b>مسألة مزاج</b> — فيتضاعف الاختبار.
  والثبات المعتدل أقوى أثرًا من الشدة المتقطعة بكثير.
</div>

<p>
