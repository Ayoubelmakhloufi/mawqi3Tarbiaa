<p>
  السنة الأولى في الميدان صعبة على الجميع، وأغلب ما يتعثر فيه الأستاذ المتدرب
  <b>ليس نقصًا في المعرفة</b> بمادته أو بعلوم التربية. هو تعثر في التنظيم:
  في تدبير الزمن، وصياغة التعليمات، وإدارة الانتقالات، وقراءة ما يجري في القسم.
  وهذه كلها قابلة للتصحيح سريعًا متى سُمّيت بأسمائها.
</p>

<h2>1. الجذاذة المكتظة</h2>

<p>
  أشيع الأخطاء وأكثرها كلفة. تخطط لخمسة أنشطة في خمس وخمسين دقيقة، فتسابق الزمن،
  فتقطع الأنشطة قبل استخلاصها، وتُلغي في النهاية <b>التقويم</b> — وهو بالضبط
  لحظة التحقق الوحيدة في الحصة.
</p>

<div class="note-ok">
  <b>العلاج:</b> هدف واحد أو اثنان للحصة، و<b>عشر دقائق محجوزة للتقويم لا تُمسّ</b>.
  إن ضاق الوقت فاحذف من البناء لا من التقويم. أن تعرف من فهم ومن لم يفهم
  أهم من أن «تُنهي» ما خططت له.
</div>

