  البدء من الأعلى يستهلك كل أدواتك في الدقيقة الأولى.
</p>

<h2>4. إعادة الشرح بدل التشخيص</h2>

<p>
  ثلث القسم لم يفهم، فتعيد الشرح بصوت أوضح وأبطأ. وغالبًا لا ينفع — لأن المشكل ليس
  في وضوح شرحك بل في <b>تمثّل راسخ</b> عند المتعلمين يناقض ما تقوله.
</p>

<p>
  التسلسل الصحيح: <b>اجمع أخطاءهم ← صنّفها ← ابحث عن منطقها المشترك ← اختر تدخلًا يناسبها</b>.
  الخطأ المنهجي المتكرر عند عدة متعلمين له قاعدة داخلية يشتغلون بها، وكشفها يوفّر عليك
  ساعات من الشرح في الاتجاه الخطأ. راجع <a href="/maqalat/bidaghojia-alkhataa">بيداغوجيا الخطأ</a>.
</p>

<h2>5. الحديث أكثر من اللازم</h2>

<p>
  يشرح المبتدئ ثلثي الحصة ظنًّا أن الشرح هو التدريس. والمتعلم الذي يستمع ثلاثين دقيقة
  متصلة لا يعالج، بل يتابع. <b>التعلم يقع حين يشتغل هو</b> لا حين تتكلم أنت.
</p>

<div class="note-info">
