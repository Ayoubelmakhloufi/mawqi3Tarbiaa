  وهي أسرع تغذية راجعة يمكنك الحصول عليها.
</div>

<h2>6. إهمال الانتقالات</h2>

<p>
  أغلب الضجيج لا يولد أثناء الأنشطة بل في <b>الفراغات بينها</b>: توزيع أوراق،
  تغيير وضعية الجلوس، انتظار المتأخرين. دقيقتان ضائعتان في كل انتقال × أربعة انتقالات
  × كل يوم = أسابيع في السنة.
</p>

<p>العلاج بسيط: إشارة متفق عليها، وتعليمة مسبقة، ومهمة قصيرة تملأ الفراغ.</p>

<h2>7. الانشغال بانطباع المؤطِّر</h2>

<p>
  حين يحضر المؤطِّر، ينشغل المتدرب بأدائه هو: هل بدوتُ متمكنًا؟ هل أعجبته الحصة؟
  وهذا يحوّل الحصة إلى <b>عرض</b>. والمؤطِّر نفسه لا يبحث عن أستاذ يؤدي دورًا،
  بل عن أستاذ يلاحظ متعلميه ويعدّل مساره حين يلزم.
</p>

<h2>8. تأجيل الوثائق والتأمل</h2>

<p>
  أخطر الأخطاء لأنه <b>غير مرئي</b>: لا يظهر أثره إلا في آخر السنة، حين تُكتب الوثائق
  من الذاكرة ويُنجز البحث في أسابيع. والخسارة الحقيقية ليست إدارية بل مهنية:
  السنة كلها مرّت بلا تراكم.
</p>

