<h2>أولًا: سلامتك أنت كأستاذ</h2>
<p>قبل تربية المتعلمين، هذه القواعد تحميك مهنيًا وقانونيًا:</p>
<ul>
  <li><b>افصل المهني عن الشخصي:</b> بريد إلكتروني للعمل وآخر شخصي، وحسابات منفصلة.</li>
  <li><b>لا تنشئ مجموعات خاصة مع المتعلمين</b> على تطبيقات المراسلة الشخصية. التواصل يمر عبر المؤسسة أو الأولياء.</li>
  <li><b>لا تشارك النقط أو اللوائح</b> عبر قنوات غير رسمية — هي معطيات شخصية محمية.</li>
  <li><b>لا تنشر صور المتعلمين</b> دون إذن مكتوب من الأولياء وموافقة الإدارة.</li>
  <li><b>أغلق جلستك</b> على الأجهزة المشتركة بقاعة الأساتذة، ولا تحفظ كلمات السر عليها.</li>
  <li><b>كلمات سر قوية ومختلفة</b> لكل خدمة، وفعّل التحقق بخطوتين حيثما أمكن.</li>
</ul>

<h2>ثانيًا: ما الذي يجب أن يتعلمه المتعلم؟</h2>

<h3>1. الأثر الرقمي</h3>
<p>
  كل ما يُنشر يترك أثرًا يصعب محوه، وقد يُقرأ بعد سنوات في سياق مختلف تمامًا.
  <b>سؤال بسيط يمكن تعليمه لأي مستوى:</b> «هل يزعجني أن يرى هذا المنشورَ والداي أو أستاذي أو من سيوظفني بعد عشر سنوات؟»
  إن كان الجواب نعم، فلا يُنشر.
</p>

<h3>2. حماية المعطيات الشخصية</h3>
<ul>
  <li>لا يُشارك: العنوان الكامل، رقم الهاتف، اسم المؤسسة مع الصورة، أوقات التنقل المعتادة.</li>
  <li>ضبط إعدادات الخصوصية في كل حساب — ومراجعتها دوريًا لأنها تتغيّر.</li>
  <li>الحذر من المسابقات والاستمارات التي تطلب معطيات مقابل جوائز.</li>
</ul>

<h3>3. التنمر الإلكتروني</h3>
<p>يختلف عن التنمر التقليدي بثلاث خصائص تجعله أشد وقعًا:</p>
<ul>
  <li><b>لا يتوقف:</b> يلاحق الضحية إلى بيتها ولا مهرب منه في المساء أو العطلة.</li>
  <li><b>ينتشر بسرعة</b> وقد يصل إلى جمهور واسع في دقائق.</li>
  <li><b>يبقى موثقًا</b> ويمكن إعادة تداوله بعد مدة طويلة.</li>
</ul>
