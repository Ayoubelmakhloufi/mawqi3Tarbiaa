<h3>1. «القدرة» — الكفاية استعداد لا فعل واحد</h3>
<p>
  لا تُستنتج الكفاية من أداء واحد ناجح. المتعلم الذي حلّ وضعية بالصدفة أو بالتقليد لم يثبت كفاية.
  ولهذا نحتاج إلى <b>أكثر من وضعية</b> قبل الحكم.
</p>

<h3>2. «تعبئة» — الكفاية فعل لا مخزون</h3>
<p>
  الفرق بين من يملك المعارف ومن هو كفء هو <b>القدرة على الاستدعاء في الوقت المناسب</b>.
