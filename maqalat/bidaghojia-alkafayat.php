  <li><b>تغيير المصطلحات دون تغيير الممارسة:</b> كتابة «كفاية» في رأس الجذاذة مع الاستمرار في نفس الدرس الإلقائي والتمارين المغلقة. أكثر الأخطاء انتشارًا وأصعبها اكتشافًا.</li>
  <li><b>وضعيات مصطنعة:</b> وضعية-مشكلة بلا معنى حقيقي للمتعلم تتحول إلى تمرين ملفوف بقصة. الاختبار: هل يهتم المتعلم فعلًا بالنتيجة؟</li>
  <li><b>إهمال الإدماج:</b> تدريس الموارد دون لحظة يجمعها فيها المتعلم.</li>
  <li><b>تقويم لا يشبه التعلم:</b> تدريس بالكفايات ثم اختبار بأسئلة استظهار — فيعود المتعلم إلى الحفظ لأنه <b>ما يُكافأ عليه</b>. المتعلمون يتعلمون ما نقوّمه لا ما ندرّسه.</li>
  <li><b>الكفاية الفضفاضة:</b> صياغة عامة («أن يتواصل المتعلم») لا يمكن ملاحظتها ولا تقويمها، فتبقى شعارًا في الجذاذة.</li>
</ol>

<h2>كيف تبدأ عمليًا هذا الأسبوع؟</h2>
<p>لا تُغيّر كل شيء دفعة واحدة. جرّب هذا التدرج:</p>
<ol>
  <li><b>اختر وحدة واحدة</b> وحدّد كفايتها بصياغة رباعية واضحة.</li>
  <li><b>اجرد الموارد اللازمة</b> لها: أي معارف؟ أي مهارات؟ أي مواقف؟</li>
  <li><b>خصّص حصة واحدة للإدماج</b> في نهاية الوحدة بوضعية-مشكلة جديدة.</li>
  <li><b>ابنِ شبكة تقويم</b> بأربعة معايير ومؤشرين لكل معيار.</li>
  <li><b>قوّم بها</b> ولاحظ الفرق بين ما يُظهره المتعلمون هنا وما تُظهره الفروض العادية.</li>
</ol>

<p>
  عند إعداد أي درس بعد اليوم، اسأل نفسك ثلاثة أسئلة: <b>ما الكفاية المستهدفة؟</b> —
  <b>ما الموارد التي تلزم لبنائها؟</b> — <b>في أي وضعية سيبرهن المتعلم أنه اكتسبها؟</b>
  إن أجبت عن الثلاثة بوضوح، فقد بنيت درسًا بالكفايات فعلًا لا اسمًا.
</p>
