  <li><b>المعرفة المُراد تدريسها:</b> بعد أن تختارها المنظومة التربوية وتنظّمها في مناهج وكتب مدرسية وأطر مرجعية.</li>
  <li><b>المعرفة المُدرَّسة فعليًا:</b> ما يقدّمه الأستاذ داخل القسم بالفعل، بتأويله وأمثلته وتبسيطه.</li>
</ol>
