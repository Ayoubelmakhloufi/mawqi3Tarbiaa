<h2>التعاقد الديداكتيكي</h2>
<p>
  مجموعة <b>القواعد الضمنية</b> التي تنظّم توقعات الأستاذ والمتعلمين تجاه بعضهم في ما يخص المعرفة:
  من يسأل؟ من يصحّح؟ ما شكل الجواب المقبول؟ متى يحق للمتعلم أن يقول «لا أعرف»؟
  هل كل سؤال له جواب واحد؟
</p>
<p>
  خطورته أنه <b>غير معلن</b>، فقد يتعلّم المتعلم <b>قراءة توقعات الأستاذ</b> بدل بناء المعرفة —
  كأن يجيب بما يظنه مطلوبًا لا بما يفهمه، أو يفترض أن كل مسألة قابلة للحل لأن الأستاذ طرحها.
</p>
<p><b>كيف تكسره بوعي؟</b></p>
<ul>
  <li>اطرح أحيانًا مسألة <b>بلا حل</b> أو بمعطيات ناقصة، وناقش معهم لماذا.</li>
  <li>اطرح سؤالًا <b>مفتوحًا بأجوبة متعددة صحيحة</b>.</li>
  <li>اقبل «لا أعرف» كجواب مشروع يُبنى عليه، ولا تعاقب عليه.</li>
  <li>اجعل التصحيح أحيانًا مسؤولية المجموعة لا مسؤوليتك وحدك.</li>
</ul>

