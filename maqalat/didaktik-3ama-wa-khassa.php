<h2>الوضعية-المشكلة</h2>
<p>حجر الزاوية في <a href="/maqalat/bidaghojia-alkafayat">التدريس بالكفايات</a>. شروط الوضعية الجيدة:</p>
<ul>
  <li><b>لها معنى</b> بالنسبة للمتعلم وتنتمي إلى سياق دال يهمّه فعلًا.</li>
  <li><b>تتضمن عائقًا حقيقيًا</b> لا يُتجاوز بالمعارف الحالية وحدها.</li>
  <li><b>في متناوله</b> — داخل منطقة نموه القريبة، فلا هي سهلة ولا مستحيلة.</li>
  <li><b>مفتوحة على أكثر من مسار حل</b> وتستدعي التفكير والتعاون والتبرير.</li>
  <li><b>تنتهي بإنتاج ملموس</b> يمكن تقويمه بمعايير واضحة.</li>
</ul>

<h3>بنية الوضعية-المشكلة</h3>
<p>الوضعية المكتملة تتكون من ثلاثة عناصر يجب أن تظهر في صياغتك:</p>
<ol>
  <li><b>السند (الحامل):</b> السياق والمعطيات — نص، صورة، جدول، وضعية واقعية.</li>
  <li><b>التعليمة:</b> ما هو المطلوب بالضبط، بصياغة واضحة لا تحتمل تأويلين.</li>
  <li><b>المهمة:</b> الإنتاج المنتظر وشروطه (الحجم، الشكل، المعايير).</li>
</ol>

