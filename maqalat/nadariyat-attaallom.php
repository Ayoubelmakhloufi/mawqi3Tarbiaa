<h2>1. النظرية السلوكية</h2>
<p>
  روّادها <b>جون واطسون</b>، <b>إيفان بافلوف</b>، و<b>بورهوس سكينر</b>. تنظر إلى التعلم باعتباره
  <b>تغيّرًا في السلوك القابل للملاحظة</b> نتيجة علاقة بين مثير واستجابة، يُثبَّت بالتعزيز.
  العقل عندها «صندوق أسود» لا يُبحث في داخله لأنه غير قابل للملاحظة المباشرة.
</p>

<h3>المفاهيم المفتاحية</h3>
<ul>
  <li><b>الإشراط الكلاسيكي</b> (بافلوف): اقتران مثير محايد بمثير طبيعي حتى يستدعي الاستجابة وحده.</li>
  <li><b>الإشراط الإجرائي</b> (سكينر): السلوك الذي يُعزَّز يتكرر، والذي يُهمَل ينطفئ.</li>
  <li><b>التعزيز الإيجابي والسلبي</b>، و<b>العقاب</b> — وليست مترادفة كما يُظن.</li>
  <li><b>التعليم المبرمج</b>: تقسيم المحتوى إلى خطوات صغيرة متدرجة بتغذية راجعة فورية.</li>
</ul>

<h3>كيف تظهر في القسم؟</h3>
<ul>
  <li>تقسيم التعلم إلى خطوات صغيرة متدرجة يتقن كل واحدة قبل الانتقال.</li>
  <li>التكرار والتمرين المكثف حتى الأتمتة.</li>
  <li>التعزيز الفوري: تشجيع لفظي، نقطة، رمز إيجابي، لوحة الشرف.</li>
  <li>صياغة الأهداف بأفعال سلوكية قابلة للملاحظة (انظر <a href="/maqalat/kayfa-tabni-jadada">بناء الجذاذة</a>).</li>
</ul>

<div class="note-info">
