  التعزيز الخارجي قد يُضعف <b>الدافعية الداخلية</b> — يشتغل المتعلم من أجل النقطة لا من أجل التعلم.
</p>

<h2>2. النظرية الجشطلتية</h2>
<p>
  روّادها <b>ماكس فيرتهايمر</b>، <b>فولفغانغ كوهلر</b>، و<b>كورت كوفكا</b>. ترى أن التعلم يحدث
  بـ<b>الاستبصار</b> — الفهم المفاجئ للعلاقة بين عناصر الوضعية — لا بالمحاولة والخطأ العشوائية.
</p>

<h3>المبادئ الأساسية</h3>
<ul>
  <li><b>الكل أكبر من مجموع الأجزاء:</b> المتعلم يدرك البنية الشاملة قبل التفاصيل.</li>
  <li><b>الاستبصار:</b> إعادة تنظيم مفاجئة لعناصر المشكل تنتج الحل («آه، فهمت!»).</li>
  <li><b>الانتقال (النقل):</b> ما يُفهم بالاستبصار ينتقل إلى وضعيات مشابهة، بخلاف ما يُحفظ آليًا.</li>
  <li><b>قوانين التنظيم الإدراكي:</b> التقارب، التشابه، الإغلاق، الاستمرارية.</li>
</ul>

<h3>كيف تظهر في القسم؟</h3>
<ul>
  <li>تقديم الظاهرة في <b>سياقها الكامل</b> قبل تفكيكها، لا العكس.</li>
  <li>الانطلاق من وضعية دالة تُبرز العلاقات بين العناصر.</li>
  <li>الاهتمام بالتنظيم البصري والمنطقي: خطاطات، جداول، خرائط ذهنية.</li>
  <li>إعطاء وقت للتأمل قبل التدخل — الاستبصار يحتاج صمتًا لا استعجالًا.</li>
</ul>

<h2>3. النظرية البنائية</h2>
<p>
