</p>

<ul>
  <li><b>اسأل عن «لماذا» لا عن «كيف».</b> «لماذا وزّعتهم هكذا؟» تعلّمك أكثر من «كيف أوزّعهم؟».</li>
  <li><b>اطلب ملاحظة على شيء محدد</b> قبل الحصة: «راقب من فضلك تعليماتي وحدها اليوم». الملاحظة المركّزة أنفع من التقييم العام.</li>
  <li><b>حوّل النقد إلى سلوك.</b> كل ملاحظة عامة اطلب تدقيقها حتى تصير إجراءً يمكنك تغييره غدًا.</li>
</ul>

