<h2>ما الذي تغيّره النظرية عمليًا؟</h2>
<p>
  المدرسة التقليدية تقوّم أساسًا <b>الذكاء اللغوي والمنطقي-الرياضي</b>. من يتفوق فيهما «ذكي»،
  ومن لا يتفوق «ضعيف» — حتى لو كان بارعًا في ستة مجالات أخرى.
</p>
<div class="note-ok">
  النظرية تقترح تعديلين بسيطين لكن عميقي الأثر:
  <br>1. <b>نوّع مداخل تقديم المفهوم</b> حتى تصل إليه من أكثر من باب.
  <br>2. <b>نوّع أشكال إثبات التعلم</b> حتى لا يُظلم من يعرف ويعجز عن التعبير بالشكل الوحيد المعتاد.
</div>

