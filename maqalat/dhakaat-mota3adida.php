  <li>الأدلة على <b>استقلال</b> هذه الذكاءات عصبيًا غير حاسمة.</li>
  <li>لم تُحسم فعالية <b>التدريس المبني عليها</b> مقارنة بالتدريس الجيد عمومًا.</li>
</ul>
