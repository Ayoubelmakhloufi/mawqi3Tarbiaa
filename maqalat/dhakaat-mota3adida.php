<h2>⚠️ سوء الاستعمال الأخطر</h2>
<div class="note">
  <b>لا تصنّف متعلميك.</b> عبارة «هذا متعلم بصري» أو «هذه ذكاؤها حركي» هي أسوأ ما يمكن
  أن تُستعمل فيه النظرية، و<b>غاردنر نفسه حذّر منها صراحة</b>.
  <br><br>
  <b>لماذا؟</b> لأن كل متعلم يملك <b>كل الذكاءات</b> بدرجات متفاوتة وقابلة للتطور.
  ووسمه بواحد منها يغلق أمامه الأبواب الأخرى، ويمنحه ذريعة جاهزة («أنا لست منطقيًا»)،
  ويعفيك من تطوير جوانبه الضعيفة — وهي بالضبط ما يحتاج تطويره.
</div>

