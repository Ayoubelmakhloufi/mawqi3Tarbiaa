<h2>ماذا بعد التقويم؟ الدعم والمعالجة</h2>
<p>تقويم لا يُبنى عليه تدخل هو إهدار للوقت. بعد التشخيص أو التقويم التكويني تأتي المعالجة:</p>
<ol>
  <li>
    <b>صنّف التعثرات حسب مصدرها</b> لا حسب حدّتها:
    <ul>
      <li><b>لغوي:</b> لم يفهم صياغة السؤال أصلًا.</li>
      <li><b>مفاهيمي:</b> المفهوم نفسه غير مبنيّ أو مبنيّ خطأ.</li>
      <li><b>منهجي:</b> يعرف المضمون ويجهل كيف ينظّم إجابته.</li>
      <li><b>ناتج عن عائق إبستيمولوجي:</b> تمثّل سابق راسخ يقاوم — انظر <a href="/maqalat/didaktik-3ama-wa-khassa">الديداكتيك</a>.</li>
    </ul>
  </li>
  <li><b>جمّع المتعلمين حسب نوع التعثر</b> لا حسب المستوى العام.</li>
  <li><b>اختر التدخل المناسب</b> لكل مجموعة — وهنا تلتقي بـ<a href="/maqalat/bidaghojia-alfariqiya">البيداغوجيا الفارقية</a>.</li>
  <li><b>أعد التقويم</b> للتحقق من أثر التدخل — وإلا فأنت تخمّن لا تعالج.</li>
</ol>

<h2>معايير جودة أي أداة تقويم</h2>
<ul>
  <li><b>الصدق:</b> هل تقيس فعلًا ما تدّعي قياسه؟ سؤال يقيس فهم النص لا سرعة القراءة مثلًا.</li>
  <li><b>الثبات:</b> هل تعطي النتيجة نفسها لو أُعيدت في ظروف مماثلة أو صحّحها مصحّح آخر؟</li>
  <li><b>الموضوعية:</b> هل النتيجة مستقلة عن ذاتية المصحّح؟ وهنا تلزم <b>شبكة تصحيح بمعايير ومؤشرات</b>.</li>
  <li><b>القابلية للتطبيق:</b> هل هي واقعية زمنيًا وماديًا في ظروف قسمك الحقيقية؟</li>
  <li><b>التمييز:</b> هل تفرّق بين مستويات الإتقان أم يحصل الجميع على النتيجة نفسها؟</li>
</ul>

<h2>كيف تدمج التقويم التكويني دون عبء إضافي؟</h2>
<p>أكبر عائق هو الوقت. جرّب هذه التقنيات التي لا تكلّف دقائق إضافية:</p>
<ul>
  <li><b>بطاقة الخروج:</b> في آخر 3 دقائق، يكتب كل متعلم على قصاصة ما فهمه وما بقي غامضًا. تقرأها في دقيقتين وتبدأ الحصة القادمة بها.</li>
  <li><b>الإبهام الثلاثي:</b> بعد كل مرحلة، إبهام لأعلى / أفقي / لأسفل. صورة فورية عن حالة القسم.</li>
  <li><b>اللوحات الصغيرة:</b> يكتب الجميع الجواب ويرفعونه معًا — ترى كل الأخطاء دفعة واحدة.</li>
  <li><b>الجولة الملاحِظة:</b> بينما يشتغلون، تمرّ بشبكة تتبع لثلاثة متعلمين فقط في كل حصة — بعد أسبوعين تكون غطّيت القسم.</li>
</ul>

