<h2>3. التقويم الإجمالي</h2>
<p><b>متى؟</b> في نهاية وحدة أو دورة أو سنة.</p>
<p>
  <b>لماذا؟</b> لإصدار حكم على درجة تحقق الكفايات المستهدفة، واتخاذ قرار: نجاح، انتقال، توجيه، إشهاد.
</p>
<p><b>أدواته:</b> الفروض المحروسة، الامتحانات الموحدة، المشاريع النهائية، الملف الوثائقي للمتعلم.</p>
<p>
  شرط صدقه أن يكون <b>ممثِّلًا لما دُرِّس فعلًا</b> ومطابقًا للإطار المرجعي، وأن يقيس
  <a href="/maqalat/bidaghojia-alkafayat">الكفاية</a> في وضعية جديدة لا أن يطلب استظهار ما حُفظ.
</p>
