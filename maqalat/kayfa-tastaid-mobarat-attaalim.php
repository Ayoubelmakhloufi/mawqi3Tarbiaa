<h2>التحضير للاختبار الشفوي</h2>
<p>اشتغل على ثلاثة محاور، وجهّز لكل واحد إجابة مبنية لا مرتجلة:</p>
<h3>1. دوافعك</h3>
<p>
  «لماذا التدريس؟» جواب صادق ومحدد أقوى من كلام إنشائي عام. اربطها بتجربة حقيقية:
  أستاذ أثّر فيك، تجربة دعم قمت بها، ملاحظة عايشتها. تجنّب العبارات الجاهزة من نوع
  «رسالة سامية» بلا مضمون.
</p>
<h3>2. تصوّرك المهني</h3>
<p>
  أي أستاذ تريد أن تكون؟ كيف تتعامل مع متعلم متعثر؟ مع قسم مكتظ؟ مع ولي أمر غاضب؟
  مع زميل يخالفك؟ جهّز لكل حالة تصورًا مبنيًا على مفاهيم تربوية لا على انطباع شخصي.
</p>
<h3>3. معرفتك بالمنظومة</h3>
<p>
  أن تكون قادرًا على الحديث عن مستجدات القطاع بهدوء ووضوح، دون مبالغة في المدح ولا في النقد.
  اللجنة تقدّر <b>الاتزان والموضوعية</b>.
</p>
<p>
  وتمرّن على <b>الشكل</b> أيضًا: التحدث بصوت مسموع، بلغة سليمة، مع تنظيم الجواب في نقاط
  (أولًا… ثانيًا…). سجّل نفسك بالهاتف وأعد الاستماع — ستكتشف تفاصيل لا تراها وأنت تتكلم.
</p>

