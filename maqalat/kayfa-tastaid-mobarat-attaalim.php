  <li><b>التحليل:</b> حلّل الوضعية بهذه المفاهيم واستخرج مصدر المشكل بدقة، لا وصفه فقط.</li>
  <li><b>الاقتراح:</b> قدّم تدخلًا <b>عمليًا وقابلًا للتنفيذ</b> في ظروف قسم مغربي واقعي، مرتبطًا بالتحليل.</li>
