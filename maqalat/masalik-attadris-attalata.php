<h2>1. التعليم الابتدائي</h2>

<h3>ما الذي يميّزه؟</h3>
<p>
  أنت <b>الأستاذ الوحيد تقريبًا</b> لقسمك: تدرّس اللغة والرياضيات والنشاط العلمي والاجتماعيات
  والتربية الإسلامية… لنفس المجموعة طوال السنة.
</p>
<p>
  ومن هنا خصوصيته: <b>تخصصك الحقيقي هو الطفل لا المادة</b>. أنت تبني الأساس الذي سيُبنى عليه
  كل ما بعده، وتعرف كل متعلم في قسمك معرفة عميقة تسمح بتتبع دقيق.
</p>

<h3>يناسبك إن…</h3>
<ul>
  <li>تستمتع بالعمل مع الأطفال الصغار وتملك صبرًا عليهم.</li>
  <li>تفضّل <b>التنويع</b> على التعمق في مادة واحدة.</li>
  <li>تحب أن ترى <b>أثرك واضحًا</b>: طفل لا يقرأ في شتنبر يقرأ في يونيو.</li>
  <li>لا تمانع تحضير عدة مواد مختلفة يوميًا.</li>
</ul>

<h3>تحدياته الحقيقية</h3>
<ul>
  <li><b>عبء التحضير</b> لعدة مواد — أثقل ما في السلك.</li>
  <li><b>الأقسام المشتركة</b> في العالم القروي (مستويان أو أكثر في قاعة واحدة).</li>
  <li>الاكتظاظ وضعف الوسائل في بعض المؤسسات.</li>
  <li>تدبير سلوك أطفال صغار يتطلب طاقة متواصلة.</li>
</ul>

<h2>2. التعليم الثانوي الإعدادي</h2>

<h3>ما الذي يميّزه؟</h3>
<p>
  تدرّس <b>تخصصًا واحدًا</b> لعدة أقسام. تتعمق في مادتك بدل تشتيت جهدك،
  لكنك تتعامل مع <b>مئات المتعلمين</b> في مرحلة المراهقة المبكرة.
</p>

<h3>يناسبك إن…</h3>
<ul>
  <li>تحب مادتك وتريد التخصص فيها.</li>
  <li>تملك قدرة على <b>تدبير المراهقين</b> — وهي مهارة تُتعلَّم لكنها تحتاج استعدادًا.</li>
  <li>تفضّل تحضيرًا واحدًا يُعاد على عدة أقسام.</li>
</ul>

<h3>تحدياته الحقيقية</h3>
<ul>
  <li><b>المراهقة المبكرة</b> — أصعب مرحلة في تدبير السلوك بشهادة أغلب الممارسين.</li>
  <li><b>الفوارق الفردية الحادة</b>: في القسم من يقرأ بطلاقة ومن يعاني الأساسيات.</li>
  <li>صعوبة معرفة كل متعلم بعمق مع مئات الأسماء.</li>
  <li>الامتحان الجهوي في السنة الثالثة وضغطه.</li>
</ul>

<h2>3. التعليم الثانوي التأهيلي</h2>

<h3>ما الذي يميّزه؟</h3>
<p>
  <b>أعلى درجة تعمق</b> في المادة. متعلمون أنضج نسبيًا ومقبلون على الباكالوريا والتوجيه الجامعي،
  فالعلاقة أقرب إلى علاقة أستاذ بطلبة منها إلى علاقة تربوية بحتة.
</p>

<h3>يناسبك إن…</h3>
<ul>
  <li>شغوف بمادتك وتريد تدريسها في مستوى متقدم.</li>
  <li>تستمتع بالنقاش الفكري والتحليل مع متعلمين قادرين عليه.</li>
  <li>تحب <b>مواكبة مصيرية</b>: توجيه متعلم نحو مساره الجامعي.</li>
</ul>

<h3>تحدياته الحقيقية</h3>
<ul>
  <li><b>ضغط الباكالوريا</b> والمسؤولية عن نتائج مصيرية.</li>
  <li>ضرورة <b>تحيين مستمر</b> لمعارفك في تخصصك.</li>
  <li>متعلمون قد يكونون منسحبين أو غير مقتنعين بالمسار.</li>
  <li>الأطر المرجعية الدقيقة التي تفرض إيقاعًا صارمًا.</li>
</ul>

