<h2>حدود التصنيف</h2>
<p>
  التصنيف أداة لا عقيدة، وله انتقادات مشروعة يجب أن تعرفها:
</p>
<ul>
  <li><b>الهرمية ليست صارمة:</b> يمكن للمتعلم أن يبدع دون إتقان كل مستويات التذكر.</li>
  <li><b>المستويات متداخلة</b> في الأداء الحقيقي لا منفصلة كما يوحي الهرم.</li>
  <li><b>لا يغطي</b> المجالين الوجداني والحسي-حركي (لهما تصنيفان مستقلان).</li>
  <li><b>لا يُستعمل لتصنيف المتعلمين</b> — هو تصنيف للأسئلة والأهداف لا للأشخاص.</li>
</ul>

