<h2>كيف توظّفه عمليًا؟</h2>

<h3>1. في صياغة أهدافك</h3>
<p>
  اختر الفعل الإجرائي بوعي بمستواه. «أن يعدّد المتعلم أنواع التقويم» هدف في مستوى التذكر،
  و«أن يميّز بين التقويم التكويني والإجمالي في وضعيات معطاة» في مستوى التحليل.
  راجع <a href="/maqalat/kayfa-tabni-jadada">بناء الجذاذة</a> لصياغة الأهداف.
</p>

