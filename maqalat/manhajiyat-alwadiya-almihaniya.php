<h2>الخطوة 4 — التقويم (ما يميّزك)</h2>
<p>
  أغلب المترشحين يتوقفون عند الاقتراح. <b>الخطوة الرابعة هي فرصتك للتميّز</b>:
</p>
<ul>
  <li><b>بأي أداة</b> تتحقق؟ (رائز قصير · شبكة ملاحظة · إنتاج مقارن)</li>
  <li><b>متى؟</b> (نهاية الحصة · بعد أسبوع · في التقويم الموالي)</li>
  <li><b>ما مؤشر النجاح؟</b> (تراجع الخطأ من ثلث القسم إلى أقل من الخمس مثلًا)</li>
  <li><b>وماذا لو لم ينجح التدخل؟</b> (خطة بديلة)</li>
</ul>

<h2>نموذج كامل محلول</h2>

<div class="note-info">
  <b>الوضعية:</b> «لاحظتَ أن ثلث متعلمي قسمك (السنة السادسة ابتدائي) يجيبون أن ناتج
  <b>8 × 0.5</b> يساوي 16، رغم إعادتك الشرح مرتين. حلّل الوضعية واقترح تدخلًا بيداغوجيًا.»
</div>

<h3>1. التأطير</h3>
<p>
  تندرج هذه الوضعية في مجال <b>الديداكتيك الخاصة بالرياضيات</b> و<b>بيداغوجيا الخطأ</b>،
  وتستدعي مفاهيم <b>التمثّلات</b> و<b>العائق الإبستيمولوجي</b> و<b>الصراع المعرفي</b>،
  إضافة إلى <b>المعالجة البيداغوجية</b> في شقها الفارقي.
</p>

<h3>2. التحليل</h3>
<p>
  الجواب «16» ليس خطأ حسابيًا عشوائيًا: 8 × 2 = 16، أي أن المتعلم <b>حوّل 0.5 إلى 2</b>
  ليجعل النتيجة أكبر من العدد الأصلي. هذا يكشف تمثّلًا راسخًا مفاده أن
  <b>«الضرب يكبّر دائمًا»</b>، بُني من كل تجارب الضرب السابقة في الأعداد الصحيحة.
</p>
<p>
  وتكرار الخطأ بعد إعادة الشرح مرتين <b>يستبعد فرضية عدم الانتباه</b> ويؤكد أننا أمام
  <b>عائق إبستيمولوجي</b> بمفهوم باشلار: معرفة سابقة منسجمة في نظر المتعلم وكافية له،
  فهي تقاوم المعرفة الجديدة بدل أن تستقبلها. ومن هنا عقم إعادة الشرح مهما تكررت.
</p>
<p>
  وكون الظاهرة تشمل <b>ثلث القسم</b> يعني أنها ليست تعثرًا فرديًا بل
  <b>مؤشرًا على أن بناء المفهوم لم يعالج هذا العائق أصلًا</b>.
</p>

<h3>3. الاقتراح</h3>
<p>أبني تدخلًا على <b>الصراع المعرفي</b> في ثلاث مراحل:</p>
<ol>
  <li>
    <b>إظهار التمثّل:</b> أطرح السؤال على القسم وأدوّن الجوابين (16 و4) على السبورة
    <b>دون تصحيح</b>، وأسأل: «أيهما الصحيح؟ ولماذا؟» — فيصير الخطأ مادة نقاش جماعي لا وصمة فردية.
  </li>
  <li>
    <b>إحداث الصراع:</b> أنتقل إلى وضعية محسوسة: «عندنا 8 قوارير، وكل واحد يشرب <b>نصف</b> قارورة.
    كم قارورة نحتاج؟» — هنا يكتشف المتعلم بنفسه أن النتيجة <b>أصغر</b>، فيفشل تفسيره القديم أمام عينيه.
  </li>
  <li>
    <b>إعادة البناء:</b> نصوغ معًا القاعدة الجديدة: الضرب في عدد <b>أصغر من 1</b> يُصغّر،
    ثم أثبّتها بوضعيات متنوعة (0.5 · 0.25 · 1.5) حتى لا يعود التمثّل القديم.
  </li>
</ol>
<p>
  وأنظّم المرحلتين الأخيرتين في <b>مجموعتَي حاجة</b>: مجموعة المتعثرين معي بدعامة محسوسة،
  ومجموعة المتمكنين على وضعيات إثراء تتضمن الضرب في أعداد عشرية أكبر وأصغر من 1 معًا.
</p>

<h3>4. التقويم</h3>
<p>
  أتحقق بـ<b>رائز قصير في نهاية الحصة</b>: ثلاث عمليات ضرب في أعداد عشرية
  (واحدة أصغر من 1، وواحدة أكبر، وواحدة تساوي 1) <b>مع مطالبة المتعلم بتوقّع</b> إن كانت النتيجة
  ستكبر أم تصغر <b>قبل</b> الحساب — لأن التوقّع هو ما يكشف التمثّل لا الحساب.
</p>
<p>
  <b>مؤشر النجاح:</b> تراجع الخطأ إلى أقل من خُمس القسم. وأعيد الاختبار بعد أسبوع للتأكد من
  ثبات المكتسب، لأن العوائق تعود بعد فترة. <b>وإن استمر التعثر</b> عند مجموعة صغيرة،
  أنتقل إلى دعم فردي بوسيط محسوس أطول مدى.
</p>

<h2>خمسة أخطاء تُكلّفك نقطًا</h2>
<ol>
  <li><b>الوصف بدل التحليل</b> — الخطأ الأول والأكثر كلفة.</li>
  <li><b>رصف المصطلحات</b> بلا توظيف في تحليل محدد.</li>
  <li><b>اقتراح منفصل عن التحليل</b> — وصفات عامة تصلح لأي وضعية فلا تصلح لأي واحدة.</li>
  <li><b>إهمال خطوة التقويم</b> — وهي أسهل ما يميّزك.</li>
  <li><b>حلول غير واقعية</b> تتجاهل الاكتظاظ ومحدودية الوسائل والزمن.</li>
</ol>

