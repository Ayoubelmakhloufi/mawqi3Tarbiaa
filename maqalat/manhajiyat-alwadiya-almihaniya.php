<h2>الخطوة 1 — التأطير</h2>
<p>
  ابدأ بتسمية <b>المفاهيم التي تحكم الوضعية</b>. جملتان أو ثلاث تكفي، لكنها تضع القارئ
  في إطارك النظري وتُظهر أنك تقرأ الوضعية بعين مهنية.
</p>
<div class="note-info">
  <b>صيغة جاهزة:</b> «تندرج هذه الوضعية في مجال [التقويم / تدبير الفصل / الفوارق الفردية]،
  وتستدعي بالتحديد مفاهيم [كذا وكذا].»
</div>
<p>
  ⚠️ <b>لا ترصف المصطلحات هنا.</b> اذكر ما ستوظّفه فعلًا في التحليل — وكل مصطلح تذكره ولا
  تستعمله لاحقًا يُضعف ورقتك لا يقوّيها.
</p>

