  <li>إنتاج <b>تمارين متدرجة</b> بثلاثة مستويات لدعم <a href="/maqalat/bidaghojia-alfariqiya">البيداغوجيا الفارقية</a>.</li>
  <li>صياغة <b>شبكات تقويم</b> بمعايير ومؤشرات انطلاقًا من كفاية تصفها له.</li>
  <li><b>تبسيط نص</b> إلى مستوى لغوي أدنى مع الحفاظ على المضمون.</li>
  <li>اقتراح <b>أسئلة تمهيدية</b> محفّزة لبداية الحصة.</li>
</ul>

<h3>2. التنويع والإثراء</h3>
<ul>
